import { test, expect } from '@playwright/test';
import { createTestPersonas } from '../persona-identity';
import { nsecSession, seedSession } from '../lib';
import { readFile } from 'node:fs/promises';

// Session seeding carries private keys. Never capture Playwright API arguments or browser storage.
test.use({ trace: 'off', video: 'off', screenshot: 'off' });

for (const administration of [false, true]) test(administration ? 'Concord role delegation' : 'Concord shared shell, encrypted messages, files and cache restoration', async ({ browser, baseURL }) => {
  test.setTimeout(240_000);
  const personas = createTestPersonas();
  const ownerContext = await browser.newContext({ baseURL });
  const memberContext = await browser.newContext({ baseURL });
  ownerContext.setDefaultTimeout(30_000);
  memberContext.setDefaultTimeout(30_000);
  try {
    await seedSession(ownerContext, nsecSession(personas.owner));
    await seedSession(memberContext, nsecSession(personas.member));
    const owner = await ownerContext.newPage();
    const member = await memberContext.newPage();
    member.on('pageerror', error => console.error(error.message.replace(/nsec1[a-z0-9]+|\b[0-9a-f]{64}\b/g, '[redacted]')));
    owner.on('pageerror', error => console.error(error.message.replace(/nsec1[a-z0-9]+|\b[0-9a-f]{64}\b/g, '[redacted]')));
    owner.on('console', message => { if (message.type() === 'error' && /^Concord (startup|grant):/.test(message.text())) console.error(message.text()); });
    await owner.goto('/app');
    await owner.getByTestId('analytics-consent').getByRole('button', { name: "Don't allow", exact: true }).click({ noWaitAfter: true });
    await owner.locator('[data-tour=rail-add-relay]').click({ timeout: 60_000 });
    await owner.getByRole('tab', { name: 'Encrypted', exact: true }).click();
    await expect(owner.getByRole('button', { name: 'Create Concord community', exact: true })).toBeVisible();
    await owner.getByRole('dialog').screenshot({ path: '/tmp/obelisk-community-picker.png' });
    await owner.getByRole('button', { name: 'Create Concord community', exact: true }).click();
    const communityName = `Obelisk E2E ${Date.now()}`;
    await owner.getByTestId('concord-name').fill(communityName, { timeout: 60_000 });
    await owner.getByTestId('concord-create').click();
    await expect(owner.getByTestId('concord-room')).toBeVisible({ timeout: 90_000 });
    await expect(owner.getByRole('dialog')).toHaveCount(0);
    await owner.getByRole('button', { name: 'Channel settings', exact: true }).click();
    await expect(owner.getByTestId('concord-channel-name')).toHaveCount(0);
    await expect(owner.getByTestId('concord-role-name')).toHaveCount(0);
    await owner.getByTestId('concord-role-settings').click();
    await expect(owner.getByTestId('concord-role-name')).toBeVisible();
    await expect(owner.getByTestId('concord-community-title')).toHaveCount(0);
    await owner.getByRole('dialog').getByRole('button', { name: 'Back', exact: true }).click();
    await owner.getByTestId('concord-community-title').fill(`${communityName} renamed`);
    await owner.getByLabel('Upload banner', { exact: true }).setInputFiles('public/icon-192.png');
    await owner.getByTestId('concord-branding-save').click();
    await expect(owner.getByTestId('sidebar-header')).toContainText(`${communityName} renamed`);
    await expect(owner.getByTestId('sidebar-header').locator('img')).toHaveCount(1);
    await owner.getByRole('button', { name: 'Channel settings', exact: true }).click();
    await owner.getByTestId('concord-create-invite').click();
    await expect(owner.getByTestId('concord-invite-link')).toBeVisible({ timeout: 60_000 });
    const invitation = await owner.getByTestId('concord-invite-link').inputValue();
    await ownerContext.grantPermissions(['clipboard-read', 'clipboard-write']);
    await owner.getByRole('button', { name: 'Copy invite link', exact: true }).click();
    expect(await owner.evaluate(async value => (await navigator.clipboard.readText()) === value, invitation)).toBe(true);
    await owner.getByRole('dialog').getByRole('button', { name: 'Close', exact: true }).click();
    await member.goto(invitation);
    await member.getByTestId('analytics-consent').getByRole('button', { name: "Don't allow", exact: true }).click({ noWaitAfter: true });
    await expect(member.getByTestId('concord-invite-input')).not.toHaveValue('', { timeout: 60_000 });
    await member.getByTestId('concord-join').click();
    await expect(member.getByTestId('concord-room')).toBeVisible({ timeout: 60_000 });
    const message = `Encrypted E2E ${Date.now()}`;
    await owner.getByPlaceholder(/^Message #/).fill(message);
    await owner.getByPlaceholder(/^Message #/).press('Enter');
    await expect(member.getByTestId('concord-messages')).toContainText(message, { timeout: 30_000 });
    await member.getByPlaceholder(/^Message #/).fill(`${message} reply`);
    await member.getByPlaceholder(/^Message #/).press('Enter');
    await expect(owner.getByTestId('concord-messages')).toContainText(`${message} reply`, { timeout: 30_000 });
    const attachment = `Private attachment ${Date.now()}`;
    await owner.locator('input[type=file]').nth(1).setInputFiles({ name: 'private.txt', mimeType: 'text/plain', buffer: Buffer.from(attachment) });
    await expect(owner.getByPlaceholder(/^Message #/)).toHaveValue(/attachment:/);
    await owner.getByPlaceholder(/^Message #/).press('Enter');
    const downloadReady = member.waitForEvent('download', { timeout: 60_000 });
    await member.getByRole('button', { name: 'Download encrypted attachment', exact: true }).first().click({ timeout: 60_000 });
    const download = await downloadReady;
    const file = await download.path();
    expect(file).not.toBeNull();
    expect(await readFile(file!, 'utf8')).toBe(attachment);
    const quickChannel = `quick-${Date.now()}`;
    await owner.getByTestId('concord-channels').getByRole('button', { name: 'Create channel', exact: true }).click();
    await owner.getByTestId('create-channel-input').fill(quickChannel);
    await owner.getByTestId('create-channel-submit').click();
    await expect(owner.getByPlaceholder(`Message #${quickChannel}`)).toBeVisible();
    await expect(member.getByTestId('concord-channels')).toContainText(quickChannel);
    const channelName = `channel-${Date.now()}`;
    await owner.getByRole('button', { name: 'Channel settings', exact: true }).click();
    await owner.getByTestId('concord-channel-settings').click();
    await owner.getByTestId('concord-channel-name').fill(channelName);
    await owner.getByLabel('Category', { exact: true }).fill('Integration tests');
    await owner.getByTestId('concord-channel-create').click();
    await expect(member.getByTestId('concord-channels').getByRole('button').filter({ hasText: channelName })).toBeVisible({ timeout: 30_000 });
    await expect(member.getByTestId('concord-channels')).toContainText('Integration tests');
    if (administration) {
    await expect(member.getByTestId('concord-create-invite')).toBeHidden();
    await owner.getByRole('dialog').getByRole('button', { name: 'Back', exact: true }).click();
    await owner.getByTestId('concord-role-settings').click();
    await owner.getByTestId('concord-role-name').fill('Inviters');
    await owner.getByLabel('Invite people', { exact: true }).check();
    await owner.getByTestId('concord-role-create').click();
    await expect(owner.getByTestId('concord-role-name')).toHaveValue('', { timeout: 30_000 });
    await owner.getByRole('dialog').getByRole('button', { name: 'Close', exact: true }).click();
    await owner.getByRole('button', { name: 'Show member list', exact: true }).click();
    const memberControls = owner.locator(`[data-pubkey="${personas.member.pkHex}"]`);
    await memberControls.locator('summary').click();
    await memberControls.getByLabel('Inviters', { exact: true }).check({ timeout: 30_000 });
    await memberControls.getByRole('button', { name: 'Save roles', exact: true }).click();
    await member.getByTestId('concord-channels').getByRole('button', { name: 'Server settings', exact: true }).click();
    await expect(member.getByTestId('concord-create-invite')).toBeVisible({ timeout: 30_000 }).catch(async error => {
      console.error('Owner member controls:', await memberControls.innerText());
      throw error;
    });
    } else {
      await owner.getByRole('dialog').getByRole('button', { name: 'Close', exact: true }).click();
    }
    await member.getByTestId('concord-channels').getByRole('button').filter({ hasText: channelName }).click();
    await member.getByPlaceholder(/^Message #/).fill('Remember this channel');
    await member.getByPlaceholder(/^Message #/).press('Enter');
    await expect(member.getByTestId('concord-messages')).toContainText('Remember this channel');
    await member.reload();
    await expect(member.getByTestId('concord-room')).toBeVisible({ timeout: 60_000 });
    await expect(member.getByPlaceholder(`Message #${channelName}`)).toBeVisible();
    await expect(member.getByTestId('sidebar-header')).toContainText(`${communityName} renamed`);
    await expect(member.getByTestId('sidebar-header').locator('img')).toHaveCount(1);
    await expect(member.getByTestId('concord-messages')).toContainText('Remember this channel');
    await member.setViewportSize({ width: 390, height: 844 });
    await expect(member.getByTestId('concord-room')).toBeVisible();
    await expect(member.getByPlaceholder(`Message #${channelName}`)).toBeVisible();
    await member.screenshot({ path: '/tmp/obelisk-concord-mobile.png' });
    await member.setViewportSize({ width: 1440, height: 900 });
    await member.screenshot({ path: '/tmp/obelisk-concord-desktop.png' });
    await member.getByRole('button', { name: 'Direct messages', exact: true }).click();
    await expect(member.getByTestId('concord-room')).toBeHidden();
    await expect(member.locator('[data-tour=rail-add-relay]')).toBeVisible();
    const plaintextLeak = await member.evaluate(text => Object.values(localStorage).some(value => String(value).includes(text)), message);
    expect(plaintextLeak).toBe(false);
  } finally {
    await Promise.all([ownerContext.close(), memberContext.close()]);
  }
});
