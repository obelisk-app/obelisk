import { buildSync } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';

const result = buildSync({
  write: false,
  entryPoints: ['scripts/appearance/bootstrap.ts'],
  outfile: 'public/appearance.js',
  bundle: true,
  minify: true,
  format: 'iife',
  platform: 'browser',
  target: 'es2020',
  banner: { js: '// Generated by npm run appearance:generate. Edit the shared appearance sources.' },
});

const output = result.outputFiles[0].text;
if (process.argv.includes('--check')) {
  if (readFileSync('public/appearance.js', 'utf8') !== output) {
    throw new Error('Appearance bootstrap is stale. Run npm run appearance:generate.');
  }
} else {
  writeFileSync('public/appearance.js', output);
}
